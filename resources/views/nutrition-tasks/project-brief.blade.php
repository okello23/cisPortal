    <h2 id="micronut-project-heading" class="h4">MicroNuT-IPHL Project</h2>
    <p><strong>Project brief:</strong> MicroNuT-IPHL strengthens micronutrient testing and surveillance within Uganda’s public health laboratory system, generating timely, reliable data to guide nutrition policy and programmes.</p>
    <h3 class="h6">Objectives</h3>
    <ul class="mb-3">
        <li>Establish sustainable micronutrient surveillance using routine health services and community validation.</li>
        <li>Validate laboratory methods and strengthen quality assurance and staff capacity.</li>
        <li>Integrate nutrition, inflammation and infectious disease data through digital systems.</li>
        <li>Support national ownership and sustainable implementation.</li>
        <li>Produce evidence for food fortification, supplementation and targeted nutrition interventions.</li>
    </ul>
    <p class="mb-0"><strong>Justification:</strong> Limited access to routine micronutrient data makes deficiencies difficult to identify and monitor. Using existing laboratories, sample transport networks and digital platforms offers a practical, cost-effective approach to improving nutrition decisions.</p>
